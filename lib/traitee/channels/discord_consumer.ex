defmodule Traitee.Channels.DiscordConsumer do
  @moduledoc """
  Nostrum gateway event consumer for Discord.

  Forwards MESSAGE_CREATE events to the `Traitee.Channels.Discord`
  GenServer, which applies DM/guild policy and routes the message.
  """
  use Nostrum.Consumer

  alias Nostrum.ConsumerGroup

  require Logger

  @join_retry_ms 1_000

  # `use Nostrum.Consumer` joins the consumer group in init/1, but Nostrum is
  # started asynchronously by Traitee.Channels.Discord (the app dep is
  # `runtime: false`), so the group may not exist yet. Retry joining until
  # the Nostrum application is up.
  @impl GenServer
  def init([]) do
    config = Traitee.Config.get([:channels, :discord]) || %{}
    skip_polling = Application.get_env(:traitee, :skip_channel_polling, false)

    if config[:token] && !skip_polling do
      send(self(), :join_consumer_group)
    end

    {:ok, nil}
  end

  @impl GenServer
  def handle_info(:join_consumer_group, state) do
    if Process.whereis(ConsumerGroup) do
      ConsumerGroup.join(self())
    else
      Process.send_after(self(), :join_consumer_group, @join_retry_ms)
    end

    {:noreply, state}
  end

  # Mirrors the dispatch clause generated by `use Nostrum.Consumer`, which is
  # replaced entirely once handle_info/2 is redefined in this module.
  @impl GenServer
  def handle_info({:event, event}, state) do
    Task.start(fn ->
      try do
        __MODULE__.handle_event(event)
      rescue
        e ->
          Logger.error(
            "Error in Discord event handler: #{Exception.format(:error, e, __STACKTRACE__)}"
          )
      end
    end)

    {:noreply, state}
  end

  @impl Nostrum.Consumer
  def handle_event({:MESSAGE_CREATE, msg, _ws_state}) do
    unless msg.author.bot do
      case Process.whereis(Traitee.Channels.Discord) do
        pid when is_pid(pid) -> send(pid, {:nostrum_message, msg})
        nil -> :ok
      end
    end
  end
end
